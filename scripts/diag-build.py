Q=[]
def add(set_,unit,stem,opts,correct,exp,check):
    assert check, f"verify failed: {stem}"
    assert correct in opts and len(set(opts))==len(opts)
    rnd=random.Random(stem); o=opts[:]; rnd.shuffle(o)
    Q.append(dict(id=f"{set_}-{sum(1 for q in Q if q['set']==set_)+1:02d}",set=set_,unit=unit,stem=stem,options=o,answer=o.index(correct)+1,explanation=exp))
lcm=lambda a,b:a*b//gcd(a,b)
def ndiv(n): return sum(1 for d in range(1,n+1) if n%d==0)
def factor(n):
    f={};p=2
    while n>1:
        while n%p==0: f[p]=f.get(p,0)+1; n//=p
        p+=1
    return f

